# === Rata-rata antar fold jadi tiga tabel importance (tanpa split train/test) ===
import numpy as np, pandas as pd
from sklearn.model_selection import StratifiedKFold as KFold
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import OneHotEncoder
from sklearn.ensemble import RandomForestClassifier as RandomForestRegressor
from sklearn.inspection import permutation_importance

# CV
cv = KFold(n_splits=5, shuffle=True, random_state=42)

# Kolom numerik & kategori dari DATA PENUH (belum split)
target = 'is_canceled'
id_cols, date_cols = ['Invoice_ID','bookingID'], ['reservation_status_date']
X_full = df_model.drop(columns=[target] + id_cols + date_cols, errors='ignore')
y_full = df_model[target].astype(int)
num_cols = X_full.select_dtypes(include=[np.number]).columns.tolist()
cat_cols = X_full.select_dtypes(include=['object','category','bool']).columns.tolist()
feat_orig = list(num_cols) + list(cat_cols)
assert len(feat_orig) > 0, "Tidak ada fitur terdeteksi di data."

# Pipeline RF sederhana utk importance (preprocess + model)
preprocess = ColumnTransformer(
  [('num', Pipeline([('imputer', SimpleImputer(strategy='median'))]), num_cols),
   ('cat', Pipeline([('imputer', SimpleImputer(strategy='most_frequent')),
                     ('ohe', OneHotEncoder(handle_unknown='ignore', sparse_output=False))]), cat_cols)],
  remainder='drop'
)
pipe_rf = Pipeline([
  ('preprocess', preprocess),
  ('model', RandomForestRegressor(n_estimators=300, max_features='sqrt',
    random_state=42, n_jobs=-1, class_weight='balanced'))
])

# helper
def group_rf_importance(pipe, num_cols, cat_cols, feat_orig):
  ct = pipe.named_steps['preprocess']
  ohe = ct.named_transformers_['cat'].named_steps['ohe'] if cat_cols else None
  names = num_cols + (list(ohe.get_feature_names_out(cat_cols)) if ohe else [])
  fi = pd.Series(pipe.named_steps['model'].feature_importances_, index=names)
  s = pd.Series(0.0, index=feat_orig)
  s.loc[num_cols] = fi.reindex(num_cols).fillna(0).values if num_cols else 0
  for c in cat_cols: s[c] = fi[fi.index.str.startswith(f'{c}_')].sum()
  return s

perm_sum = pd.Series(0.0, index=feat_orig)
rf_sum   = pd.Series(0.0, index=feat_orig)
rng = np.random.RandomState(42)

for tr, va in cv.split(X_full, y_full):
  pipe_rf.fit(X_full.iloc[tr], y_full.iloc[tr])
  yv = y_full.iloc[va]
  m  = min(12, yv.value_counts().min())  # sampel mini seimbang
  idx = np.r_[rng.choice(np.asarray(va)[yv.eq(1)], m, False),
    rng.choice(np.asarray(va)[yv.eq(0)], m, False)]
  perm = permutation_importance(pipe_rf, X_full.iloc[idx], y_full.iloc[idx],
    scoring='average_precision', n_repeats=1, n_jobs=-1, random_state=42)
  perm_sum += pd.Series(perm.importances_mean, index=feat_orig).fillna(0)
  rf_sum   += group_rf_importance(pipe_rf, num_cols, cat_cols, feat_orig)

rng = np.random.RandomState(123)

for tr, va in cv.split(X_full, y_full):
  pipe_rf.fit(X_full.iloc[tr], y_full.iloc[tr])
  yv = y_full.iloc[va]
  m  = min(80, yv.value_counts().min())   # tambah ketelitian
  idx = np.r_[rng.choice(np.asarray(va)[yv.eq(1)], m, False),
    rng.choice(np.asarray(va)[yv.eq(0)], m, False)]
  perm = permutation_importance(pipe_rf, X_full.iloc[idx], y_full.iloc[idx],
    scoring='average_precision', n_repeats=2, n_jobs=-1, random_state=123)
  perm_sum += pd.Series(perm.importances_mean, index=feat_orig).fillna(0)
  rf_sum   += group_rf_importance(pipe_rf, num_cols, cat_cols, feat_orig)

# Tiga tabel importance (rata-rata antar fold)
