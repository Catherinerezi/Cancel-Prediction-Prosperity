def net_gain_at_threshold(y_true, p, t):
  y_pred = (p >= t).astype(int)
  tn, fp, fn, tp = confusion_matrix(y_true, y_pred).ravel()
  gain = tp*C_TP + tn*C_TN - fp*C_FP - fn*C_FN
  return gain, (tn, fp, fn, tp)

