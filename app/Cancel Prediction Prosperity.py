assert hasattr(best_pipe, "predict_proba"), "best_pipe harus punya predict_proba"

# util umum
def _proba_pos(X):
  p = best_pipe.predict_proba(X)[:, 1]
  return np.clip(p, 1e-6, 1 - 1e-6)

def _logit(p):
  p = np.clip(p, 1e-6, 1 - 1e-6)
  return np.log(p / (1 - p))

# baseline logit (acuan untuk Δ)
p_base = _proba_pos(X_test)
logit_base_mean = _logit(p_base).mean()

