def split_rooms_cap4(row):
  A, C, B = map(int, (row.adults, row.children, row.babies))
  M = C + B
  rooms, viol = [], False

  # 1) kamar berisi minors (maksimal 3 minors + diatas 1 adult, total maksimal 4)
  while M > 0:
    a = 1 if A > 0 else 0
    if a == 0: viol = True # minors tanpa adult (pelanggaran)
    else: A -= 1
    take = min(3, M)
    c_take = min(C, take); b_take = min(B, take - c_take)
    C -= c_take; B -= b_take; M -= (c_take + b_take)
    extra_a = min(4 - a - c_take - b_take, A)
    A -= extra_a; a += extra_a
    rooms.append((a, c_take, b_take))

  # 2) sisa adults ke kamar adult-only (maksimal 4 adults/kamar)
  while A > 0:
    a = min(4, A); rooms.append((a, 0, 0)); A -= a

  if not rooms: rooms = [(0,0,0)]
  base = row.to_dict(); base['orig_id'] = row.name
  out = []
  for a,c,b in rooms:
    r = base.copy()
    r.update({'adults':a,'children':c,'babies':b,'viol_minors_without_adult':viol})
    out.append(r)
  return out

