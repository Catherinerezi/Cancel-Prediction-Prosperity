# fungsi PDP/ICE
rng = check_random_state(42)
sample_for_ice = min(200, len(X_test))
idx_ice = rng.choice(len(X_test), sample_for_ice, replace=False)

def pdp_ice_numeric(col, grid_resolution=30, q_low=0.02, q_high=0.98):
  x = X_test[col].astype(float)
  lo, hi = np.quantile(x, [q_low, q_high])
  grid = np.linspace(lo, hi, grid_resolution)

  # PDP (mean) pada skala Δ-logit
  deltas = []
  for v in grid:
    X_tmp = X_test.copy()
    X_tmp[col] = v
    lg = _logit(_proba_pos(X_tmp)).mean()
    deltas.append(lg - logit_base_mean)
  deltas = np.array(deltas)

  # ICE pada subset
  X_ref = X_test.iloc[idx_ice].copy()
  ice = []
  for v in grid:
    X_tmp = X_ref.copy()
    X_tmp[col] = v
    lg = _logit(_proba_pos(X_tmp)) - _logit(_proba_pos(X_ref))
    ice.append(lg)
  ice = np.vstack(ice).T
  return grid, deltas, ice

def pdp_categorical(col, top_k=15):
  vc = X_test[col].value_counts().head(top_k)
  cats = list(vc.index)
  deltas = []
  for v in cats:
    X_tmp = X_test.copy()
    X_tmp[col] = v
    lg = _logit(_proba_pos(X_tmp)).mean()
    deltas.append(lg - logit_base_mean)
  return cats, np.array(deltas)

